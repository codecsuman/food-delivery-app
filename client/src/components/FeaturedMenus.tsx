import { useEffect } from "react";
import { Link } from "react-router-dom";
import { useMenuStore } from "@/store/useMenuStore";
import { CardContent } from "./ui/card";
import { Skeleton } from "./ui/skeleton";
import { IndianRupee, Flame, Sparkles } from "lucide-react";
import { motion } from "framer-motion";
import { getImageUrl, handleImageError } from "@/lib/placeholder";
import { getRestaurantId } from "@/lib/validation";

const FeaturedMenus = () => {
  const { menus, loading, getAllMenus } = useMenuStore();

  useEffect(() => {
    getAllMenus();
  }, [getAllMenus]);

  if (!loading && menus.length === 0) {
    return null;
  }

  // Color themes for cards - cycling through orange, yellow, green, red.
  // `text` holds static Tailwind classes (dynamic class names are not
  // generated by Tailwind). `gradient` holds a real CSS value for inline
  // styles — the old code passed Tailwind class names to `background`, which
  // is invalid CSS and rendered transparent.
  const colorThemes = [
    {
      primary: "from-orange-500 to-amber-500",
      secondary: "bg-orange-50 dark:bg-orange-500/10",
      border: "border-orange-200 dark:border-orange-500/20",
      text: "text-orange-600 dark:text-orange-400",
      gradient: "linear-gradient(90deg, #f97316, #f59e0b)",
    },
    {
      primary: "from-yellow-500 to-amber-400",
      secondary: "bg-yellow-50 dark:bg-yellow-500/10",
      border: "border-yellow-200 dark:border-yellow-500/20",
      text: "text-yellow-600 dark:text-yellow-400",
      gradient: "linear-gradient(90deg, #eab308, #fbbf24)",
    },
    {
      primary: "from-emerald-500 to-teal-500",
      secondary: "bg-emerald-50 dark:bg-emerald-500/10",
      border: "border-emerald-200 dark:border-emerald-500/20",
      text: "text-emerald-600 dark:text-emerald-400",
      gradient: "linear-gradient(90deg, #10b981, #14b8a6)",
    },
    {
      primary: "from-orange-500 to-red-500",
      secondary: "bg-red-50 dark:bg-red-500/10",
      border: "border-red-200 dark:border-red-500/20",
      text: "text-red-600 dark:text-red-400",
      gradient: "linear-gradient(90deg, #f97316, #ef4444)",
    },
  ];

  // Container variants for staggered entrance animation
  const containerVariants = {
    hidden: { opacity: 0 },
    show: { opacity: 1, transition: { staggerChildren: 0.08, delayChildren: 0.2 } }
  };

  // Card variants for entrance and scroll animations
  const cardVariants = {
    hidden: { opacity: 0, y: 30, scale: 0.95 },
    show: { 
      opacity: 1, 
      y: 0, 
      scale: 1,
      transition: { duration: 0.5, type: "spring" as const, stiffness: 260, damping: 25 }
    }
  };

  // Hover variants for card lift effect
  const hoverVariants = {
    y: -8,
    scale: 1.02,
    boxShadow: "0 25px 50px -12px rgba(249, 115, 22, 0.35)",
    transition: { duration: 0.3, type: "spring" as const, stiffness: 300, damping: 30 }
  };

  return (
    <section className="max-w-7xl mx-auto px-4 md:px-10 py-10">
      {/* Header with animated background */}
      <motion.div
        initial={{ opacity: 0, y: 30 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ duration: 0.6, ease: "easeOut" }}
        className="relative mb-8"
      >
        {/* Animated gradient background */}
        <div className="absolute inset-0 bg-gradient-to-r from-orange-500/10 via-yellow-500/10 to-emerald-500/10 rounded-3xl blur-3xl animate-pulse" />
        <div className="relative flex items-center gap-3 mb-6">
          <motion.div
            initial={{ scale: 0, rotate: -180 }}
            animate={{ scale: 1, rotate: 0 }}
            transition={{ duration: 0.8, delay: 0.2, type: "spring", stiffness: 260, damping: 20 }}
            className="h-12 w-12 rounded-xl bg-gradient-to-br from-orange-500 to-amber-500 flex items-center justify-center shadow-lg shadow-orange-500/25"
          >
            <Flame className="w-6 h-6 text-white" />
          </motion.div>
          <motion.div
            initial={{ opacity: 0, x: -30 }}
            animate={{ opacity: 1, x: 0 }}
            transition={{ duration: 0.5, delay: 0.3 }}
          >
            <h2 className="text-xl md:text-2xl font-extrabold tracking-tight text-gray-900 dark:text-white bg-gradient-to-r from-orange-600 via-amber-600 to-emerald-600 bg-clip-text text-transparent">
              All Dishes
            </h2>
            <p className="text-sm text-gray-500 dark:text-gray-400 mt-1">
              Explore all dishes from restaurants near you
            </p>
          </motion.div>
        </div>
      </motion.div>

      {/* Cards Grid / Scroll - using Framer Motion variants for staggered animations */}
      <motion.div
        variants={containerVariants}
        initial="hidden"
        animate="show"
        className="flex gap-5 overflow-x-auto pb-4 -mx-4 px-4 md:mx-0 md:px-0 md:grid md:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 md:overflow-visible scrollbar-hide snap-x snap-mandatory"
      >
        {loading
          ? [...Array(6)].map((_, i) => (
              <motion.div
                key={i}
                variants={{ hidden: { opacity: 0, y: 20 }, show: { opacity: 1, y: 0, transition: { delay: i * 0.1 } }}}
                className="shrink-0 w-56 md:w-auto snap-start"
              >
                <Skeleton className="h-72 w-56 md:w-full shrink-0 rounded-2xl snap-start" />
              </motion.div>
            ))
          : menus.map((item, index) => {
            const theme = colorThemes[index % colorThemes.length];
            // `restaurant` may be a populated object or a raw id. Never build a
            // detail URL from an invalid value (that produced /restaurant/undefined
            // and a guaranteed 400 from the API).
            const restaurantId = getRestaurantId(item.restaurant);

            return (
              <motion.div
                key={item._id}
                variants={cardVariants}
                className="shrink-0 w-56 md:w-auto snap-start"
              >
                <Link
                  to={restaurantId ? `/restaurant/${restaurantId}` : "/search"}
                  className="shrink-0 w-56 md:w-auto snap-start block"
                >
                  <motion.div
                    variants={{ 
                      initial: { opacity: 1 },
                      hover: hoverVariants 
                    }}
                    initial="initial"
                    whileHover="hover"
                    className={`group bg-white dark:bg-gray-800 shadow-sm rounded-2xl overflow-hidden transition-all duration-300 hover:shadow-xl h-full flex flex-col w-full ${theme.border} ${theme.secondary}`}
                  >
                    {/* Image with theme-colored overlay */}
                    <div className="relative overflow-hidden">
                      <motion.img
                        src={getImageUrl(item.image)}
                        alt={item.name}
                        initial={{ scale: 1.1, opacity: 0 }}
                        animate={{ scale: 1, opacity: 1 }}
                        transition={{ duration: 0.8, ease: "easeOut" }}
                        whileHover={{ scale: 1.08 }}
                        className="w-full h-40 object-cover transition-transform duration-500 group-hover:scale-105"
                        loading="lazy"
                        onError={handleImageError}
                      />
                      {/* Animated gradient overlay */}
                      <motion.div
                        initial={{ opacity: 0 }}
                        whileHover={{ opacity: 0.15 }}
                        className="absolute inset-0 bg-gradient-to-t from-black/40 to-transparent"
                        transition={{ duration: 0.3 }}
                      />
                      {/* Theme accent bar at top */}
                      <div className="absolute top-0 left-0 right-0 h-1" style={{ backgroundImage: theme.gradient }} />
                      
                      {/* Popular/Order count badge with theme color */}
                      {item.orderCount && item.orderCount > 0 && (
                        <motion.div
                          initial={{ opacity: 0, scale: 0.5 }}
                          animate={{ opacity: 1, scale: 1 }}
                          transition={{ delay: 0.3, type: "spring", stiffness: 260, damping: 20 }}
                          className="absolute top-2 left-2 text-white text-xs font-bold px-2 py-1 rounded-full shadow-lg"
                          style={{ backgroundImage: theme.gradient }}
                        >
                          <Sparkles className="w-3 h-3 inline mr-1" />
                          {item.orderCount}+ orders
                        </motion.div>
                      )}
                      
                      {/* Price Badge - Solid visible color */}
                      <motion.div
                        initial={{ opacity: 0, x: 20 }}
                        animate={{ opacity: 1, x: 0 }}
                        transition={{ delay: 0.4 }}
                        className="absolute top-2 right-2 bg-white/95 dark:bg-gray-900/95 backdrop-blur-sm px-3 py-1.5 rounded-xl shadow-lg"
                      >
                        <span className="text-sm font-bold flex items-center gap-1 text-gray-900 dark:text-white">
                          <IndianRupee className="w-4 h-4 text-orange-500" />
                          ₹{item.price}
                        </span>
                      </motion.div>
                    </div>

                    {/* Content */}
                    <CardContent className="p-4 flex-1 flex flex-col">
                      <motion.h3
                        initial={{ opacity: 0, y: 10 }}
                        animate={{ opacity: 1, y: 0 }}
                        transition={{ delay: 0.5 }}
                        className="font-semibold text-gray-900 dark:text-white truncate group-hover:text-orange-600 dark:group-hover:text-orange-400 transition-colors duration-300"
                      >
                        {item.name}
                      </motion.h3>
                      <motion.p
                        initial={{ opacity: 0, y: 10 }}
                        animate={{ opacity: 1, y: 0 }}
                        transition={{ delay: 0.6 }}
                        className="text-sm text-gray-500 dark:text-gray-400 line-clamp-2 mt-1 flex-1"
                      >
                        {item.description}
                      </motion.p>
                      <motion.div
                        initial={{ opacity: 0, y: 10 }}
                        animate={{ opacity: 1, y: 0 }}
                        transition={{ delay: 0.7 }}
                        className="mt-3 pt-3 border-t border-gray-100 dark:border-gray-700 flex items-center justify-between"
                      >
                        <span className={`text-xs font-medium group-hover:underline transition-colors ${theme.text}`}>
                          View Restaurant →
                        </span>
                        {(item.restaurant && typeof item.restaurant === "object" && item.restaurant.restaurantName) && (
                          <span className="text-xs text-gray-400 dark:text-gray-500">
                            {item.restaurant.restaurantName}
                          </span>
                        )}
                      </motion.div>
                    </CardContent>

                    {/* Floating theme particles on hover */}
                    <motion.div
                      initial={{ opacity: 0 }}
                      whileHover={{ opacity: 1 }}
                      className="absolute inset-0 pointer-events-none overflow-hidden"
                      transition={{ duration: 0.3 }}
                    >
                      {[1, 2, 3].map((i) => (
                        <motion.div
                          key={i}
                          animate={{
                            y: [0, -20, -40],
                            x: [0, (i - 2) * 10],
                            opacity: [0, 1, 0],
                            scale: [0, 1, 0]
                          }}
                          transition={{
                            duration: 1.5,
                            repeat: Infinity,
                            delay: i * 0.3,
                            ease: "easeOut"
                          }}
                          className="absolute bottom-0 w-1.5 h-1.5 rounded-full"
                          style={{ 
                            left: `${25 + i * 20}%`,
                            backgroundImage: theme.gradient
                          }}
                        />
                      ))}
                    </motion.div>
                  </motion.div>
                </Link>
              </motion.div>
            );
          })}
      </motion.div>
    </section>
  );
};

export default FeaturedMenus;